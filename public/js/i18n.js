// الحصول على اللغة الحالية
function getCurrentLang() {
  return localStorage.getItem('remal_lang') || 'ar';
}

// تحديث وسوم السيو (Dynamic On-Page SEO)
function updateSEO(lang) {
  const dict = i18nDictionary[lang] || i18nDictionary.ar;

  // عنوان الصفحة
  document.title = dict.meta_title;

  // وسوم الوصف والكلمات المفتاحية
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc) metaDesc.setAttribute('content', dict.meta_description);

  let metaKeywords = document.querySelector('meta[name="keywords"]');
  if (!metaKeywords) {
    metaKeywords = document.createElement('meta');
    metaKeywords.name = 'keywords';
    document.head.appendChild(metaKeywords);
  }
  metaKeywords.setAttribute('content', dict.meta_keywords);

  // وسوم OpenGraph
  const ogTitle = document.querySelector('meta[property="og:title"]');
  if (ogTitle) ogTitle.setAttribute('content', dict.meta_title);

  const ogDesc = document.querySelector('meta[property="og:description"]');
  if (ogDesc) ogDesc.setAttribute('content', dict.meta_description);

  const ogLocale = document.querySelector('meta[property="og:locale"]');
  if (ogLocale) ogLocale.setAttribute('content', lang === 'ar' ? 'ar_SA' : 'en_US');

  // وسوم Twitter
  const twTitle = document.querySelector('meta[name="twitter:title"]');
  if (twTitle) twTitle.setAttribute('content', dict.meta_title);

  const twDesc = document.querySelector('meta[name="twitter:description"]');
  if (twDesc) twDesc.setAttribute('content', dict.meta_description);
}

// تبديل اللغة وتحديث النصوص بالكامل بدون إعادة تحميل
function setLanguage(lang) {
  if (!i18nDictionary[lang]) lang = 'ar';
  localStorage.setItem('remal_lang', lang);

  const html = document.documentElement;
  const isRtl = lang === 'ar';

  html.setAttribute('lang', lang);
  html.setAttribute('dir', isRtl ? 'rtl' : 'ltr');

  // تحديث السيو ديناميكياً
  updateSEO(lang);

  // تحديث النصوص ذات السمة data-i18n
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (i18nDictionary[lang][key]) {
      el.textContent = i18nDictionary[lang][key];
    }
  });

  // تحديث حقول الإدخال ذات السمة data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (i18nDictionary[lang][key]) {
      el.setAttribute('placeholder', i18nDictionary[lang][key]);
    }
  });

  // إشعار المكونات الديناميكية (الأقسام والماركات)
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang, isRtl } }));
}

// تبديل اللغة
function toggleLanguage() {
  const current = getCurrentLang();
  const nextLang = current === 'ar' ? 'en' : 'ar';
  setLanguage(nextLang);
}

// تهيئة اللغة عند تحميل الصفحة
document.addEventListener('DOMContentLoaded', () => {
  const savedLang = getCurrentLang();
  setLanguage(savedLang);

  document.querySelectorAll('.btn-lang-toggle').forEach((btn) => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      toggleLanguage();
    });
  });
});
